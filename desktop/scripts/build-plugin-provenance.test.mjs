import test from 'node:test'
import assert from 'node:assert/strict'

import {
  buildProvenance,
  isManaged,
  pinnedVersions,
} from './build-plugin-provenance.mjs'

const LOCKFILE = `# This file is generated by running "yarn install" inside your project.

"omnimux@npm:^0.1.3":
  version: 0.1.3
  resolution: "omnimux@npm:0.1.3"
  dependencies:
    ws: "npm:^8.21.0"

"omnimux-workflow@npm:^1.0.0-rc.2":
  version: 1.0.0-rc.2
  resolution: "omnimux-workflow@npm:1.0.0-rc.2"

"dsh-community-market@workspace:.":
  version: 0.0.0-use.local
  resolution: "dsh-community-market@workspace:."

"react@npm:^19.0.0":
  version: 19.2.0
  resolution: "react@npm:19.2.0"

"@deepseek-ai/dsh-invariants@npm:0.1.5-rc.3":
  version: 0.1.5-rc.3
  resolution: "@deepseek-ai/dsh-invariants@npm:0.1.5-rc.3"
`

test('reads the pinned version of every package', () => {
  const versions = pinnedVersions(LOCKFILE)
  assert.equal(versions.get('omnimux').version, '0.1.3')
  assert.equal(versions.get('omnimux-workflow').version, '1.0.0-rc.2')
  assert.equal(versions.get('react').version, '19.2.0')
})

test('marks a workspace package, which has no registry entry to ask', () => {
  assert.equal(pinnedVersions(LOCKFILE).get('dsh-community-market').workspace, true)
  assert.equal(pinnedVersions(LOCKFILE).get('omnimux').workspace, false)
})

test('keeps only the plugins a release ships', () => {
  assert.equal(isManaged('omnimux'), true)
  assert.equal(isManaged('omnimux-workflow'), true)
  assert.equal(isManaged('@deepseek-ai/dsh-invariants'), true)
  assert.equal(isManaged('dsh-better-sidebar'), true)
  assert.equal(isManaged('react'), false)
})

test('records each plugin with the commit its tarball was built from', () => {
  const record = buildProvenance(LOCKFILE, () => 'a'.repeat(40), { commit: 'b'.repeat(40) })
  const byName = Object.fromEntries(record.plugins.map((plugin) => [plugin.name, plugin]))
  assert.equal(byName.omnimux.commit, 'a'.repeat(40))
  assert.equal(byName.omnimux.version, '0.1.3')
  assert.equal(record.plugins.some((plugin) => plugin.name === 'react'), false)
  assert.equal(record.app.commit, 'b'.repeat(40))
})

test('a registry miss is recorded, not thrown', () => {
  const record = buildProvenance(LOCKFILE, (name) => {
    if (name === 'omnimux') throw new Error('offline')
    return null
  })
  const omnimux = record.plugins.find((plugin) => plugin.name === 'omnimux')
  assert.equal(omnimux.commit, null)
  assert.match(omnimux.note, /registry lookup failed/u)
  const workflow = record.plugins.find((plugin) => plugin.name === 'omnimux-workflow')
  assert.match(workflow.note, /no gitHead/u)
})

test('a workspace package is attributed to the application commit, not the registry', () => {
  const record = buildProvenance(LOCKFILE, () => {
    throw new Error('must not be asked about a workspace package')
  })
  const local = record.plugins.find((plugin) => plugin.name === 'dsh-community-market')
  assert.equal(local.source, 'workspace')
  assert.equal(local.commit, null)
})
