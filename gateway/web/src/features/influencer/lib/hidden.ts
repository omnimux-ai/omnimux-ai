const KEY = 'influencer:hidden-tasks'

export function hiddenTaskIds(): Set<string> {
  try {
    const raw = localStorage.getItem(KEY)
    if (!raw) return new Set()
    const arr = JSON.parse(raw)
    return new Set(Array.isArray(arr) ? arr.map(String) : [])
  } catch {
    return new Set()
  }
}

export function hideTask(taskId: string): Set<string> {
  const set = hiddenTaskIds()
  set.add(taskId)
  try {
    localStorage.setItem(KEY, JSON.stringify([...set]))
  } catch {
    /* storage may be unavailable; the task still hides for this session */
  }
  return set
}
